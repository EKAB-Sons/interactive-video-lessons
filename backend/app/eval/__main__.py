"""Run the whole harness on a data directory and write a Markdown report.

    python -m app.eval ../examples/eval ../docs/verification/eval-report.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from tests.fixtures import context_packet_fixture, proposal_fixture, scene_fixture

from . import FAULTS, learning_report, load_cases, rubric_report, run_faults, run_heldout


def _jsonl(path: Path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def main(data_dir: str, out_path: str) -> int:
    data, out = Path(data_dir), Path(out_path)
    held = run_heldout(load_cases(data / "heldout_sample.jsonl"), load_cases(data / "dev_sample.jsonl"))
    rub = rubric_report(_jsonl(data / "rubric_labels_sample.jsonl"))
    learn = learning_report(_jsonl(data / "learning_sample.jsonl"))
    faults = run_faults(proposal_fixture(), context_packet_fixture(), scene_fixture())
    synthetic = any(r.get("synthetic") for r in _jsonl(data / "heldout_sample.jsonl"))

    lines = ["# Evaluation harness report", ""]
    if synthetic:
        lines += ["> All inputs are SYNTHETIC sample data generated by `scripts/make_eval_samples.py`. ",
                  "> Numbers demonstrate the harness; they are not results about the system.", ""]
    h = held.as_dict()
    lines += ["## Held-out requests", "",
              f"- In-scope cases: {h['in_scope_total']}, passed: {h['in_scope_passed']}, pass rate: {h['pass_rate']:.1%}",
              f"- Enough cases to claim the target: {h['enough_cases_for_claim']} (target {h['target']}); meets target: {h['meets_target']}",
              f"- In-scope final statuses: {h['in_scope_status_counts']}",
              f"- Out-of-scope cases: {h['out_of_scope_total']}, correctly withheld: {h['out_of_scope_correctly_withheld']}",
              f"- Leakage findings: {h['leakage'] or 'none'}", "", "Failures (unresolved in-scope requests count as failures):", ""]
    lines += [f"- `{f['case_id']}`: {f['status']} {f['reason_codes']}" for f in h["failures"]] or ["- none"]
    lines += ["", "## Review rubric agreement", "", f"- Reviewers: {rub['reviewers']}, cases labelled by all: {rub['cases_labelled_by_all']}",
              f"- Consensus pass count: {rub['consensus_pass_count']}; disagreements: {rub['disagreements'] or 'none'}", ""]
    for pair, crit in rub["agreement"].items():
        lines.append(f"- {pair}: " + ", ".join(f"{k} agreement {v['percent_agreement']:.0%} / kappa {v['kappa']:.2f}" for k, v in crit.items()))
    lines += ["", "## Learning gain", "",
              f"- Paired participants: {learn['participants_paired']} of {learn['participants_total']}; orders: {learn['orders']}",
              f"- Mean gain: interactive {learn['mean_gain']['interactive']}, prepared {learn['mean_gain']['prepared']} (sd {learn['sd_gain']})",
              f"- Difference: {learn['difference_pp']} pp, bootstrap 95% CI {learn['bootstrap_95ci_pp']}; meets threshold: {learn['meets_threshold']}; CI excludes zero: {learn['ci_excludes_zero']}",
              f"- Gain by order: {learn['gain_by_order']}", f"- Design warnings: {learn['design_warnings'] or 'none'}", "",
              "## Seeded faults and monitoring hooks", "", "| fault | hook | expected | observed | code seen | pass |", "|---|---|---|---|---|---|"]
    for o in faults:
        lines.append(f"| {o.fault_id} | {o.hook} | {o.expected_status} | {o.observed_status} | {o.expected_code in o.observed_codes} | {'yes' if o.passed else 'NO'} |")
    lines += ["", f"{sum(o.passed for o in faults)}/{len(faults)} seeded faults surfaced at the declared hook with the declared status and code.", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0 if all(o.passed for o in faults) else 1


if __name__ == "__main__":
    sys.exit(main(*(sys.argv[1:3] or ("../examples/eval", "../docs/verification/eval-report.md"))))
